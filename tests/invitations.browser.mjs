import assert from 'node:assert/strict';
import {mkdir} from 'node:fs/promises';
import {chromium} from 'playwright-core';
import {loadConfig} from '../server/config.mjs';
import {memorySheetStore,sheetTestServer} from './sheets-fixture.mjs';
import {clientDetails} from './client-fixture.mjs';

const adminKey='browser-admin-secret-'.repeat(3);
const config=loadConfig({PAYMENTS_ENABLED:'true',RAZORPAY_KEY_ID:'rzp_test_browser',RAZORPAY_KEY_SECRET:'test-secret',RAZORPAY_WEBHOOK_SECRET:'webhook-secret',INVITATIONS_REQUIRED:'true',INVITATION_ADMIN_KEY:adminKey,SHEETS_STORE_URL:'https://script.google.com/macros/s/browser/exec',SHEETS_STORE_SECRET:'x'.repeat(64)});
const {records,store}=memorySheetStore();
config.email.enabled=true;config.email.allowTest=true;
const invitationEmails=[];
const server=sheetTestServer({config,store,provider:{},sendInvitation:async(invitation,url)=>invitationEmails.push({invitation,url})});
let browser;
try{
  await new Promise(resolve=>server.listen(0,'127.0.0.1',resolve));config.origin='http://127.0.0.1:'+server.address().port;
  browser=await chromium.launch({headless:true,...(process.env.BROWSER_EXECUTABLE_PATH?{executablePath:process.env.BROWSER_EXECUTABLE_PATH}:{channel:'msedge'})});
  const adminContext=await browser.newContext(),clientContext=await browser.newContext(),otherContext=await browser.newContext();
  const errors=[];for(const context of [adminContext,clientContext,otherContext])context.on('page',page=>page.on('pageerror',error=>errors.push(error.message)));
  const admin=await adminContext.newPage(),client=await clientContext.newPage(),other=await otherContext.newPage();
  await client.goto(config.origin);
  await client.locator('#invitation-stage').waitFor({state:'visible'});
  assert.equal(await client.locator('#client-details-stage').isVisible(),false);
  assert.equal(records.length,0);
  await client.locator('#invitation-read-agreement').click();
  assert.equal(await client.locator('#main').isVisible(),true);
  assert.equal(await client.locator('#agreement-form').evaluate(form=>form.inert),true);
  await admin.goto(config.origin+'/admin.html');
  // Hosting errors are plain text/HTML, not application JSON.
  await admin.route('**/api/payments/admin/invitations',route=>route.fulfill({status:502,contentType:'text/plain',body:'Error - Request failed'}));
  await admin.locator('#admin-key').fill(adminKey);
  await admin.locator('#admin-login button').click();
  await admin.waitForFunction(()=>document.querySelector('#admin-status').textContent.includes('HTTP 502'));
  assert.doesNotMatch(await admin.locator('#admin-status').innerText(),/Unexpected token|not valid JSON/);
  await admin.unroute('**/api/payments/admin/invitations');
  await admin.route('**/api/payments/admin/invitations',route=>route.fulfill({status:401,contentType:'text/html',body:'<html>Login Redirect</html>'}));
  await admin.locator('#admin-login button').click();
  await admin.waitForFunction(()=>document.querySelector('#admin-status').textContent.includes('Site access was blocked'));
  await admin.unroute('**/api/payments/admin/invitations');
  await admin.route('**/api/payments/admin/invitations',route=>route.fulfill({status:200,contentType:'application/json',body:'invalid JSON'}));
  await admin.locator('#admin-login button').click();
  await admin.waitForFunction(()=>document.querySelector('#admin-status').textContent.includes('invalid response'));
  await admin.unroute('**/api/payments/admin/invitations');
  await adminContext.addCookies([{name:'hosting-access-test',value:'signed-in',url:config.origin}]);
  await admin.route('**/api/payments/admin/invitations**',async route=>{
    const headers=await route.request().allHeaders();
    assert.match(headers.cookie || '',/hosting-access-test=signed-in/);
    await route.continue();
  });
  await admin.locator('#admin-key').fill('wrong-admin-key-'.repeat(3));
  await admin.locator('#admin-login button').click();
  await admin.waitForFunction(()=>document.querySelector('#admin-status').textContent.includes('denied'));
  assert.equal(await admin.locator('#admin-content').isVisible(),false);
  await admin.locator('#admin-key').fill(adminKey);
  await admin.locator('#admin-login button').click();
  await admin.locator('#admin-content').waitFor({state:'visible'});
  assert.equal(await admin.locator('#admin-environment').count(),0);
  assert.match(await admin.locator('#invitation-email-settings').innerText(),/email is enabled/);
  assert.equal(await admin.locator('#invitation-create button').innerText(),'Create and email invitation');
  assert.equal(await admin.locator('#admin-key').inputValue(),'');
  await admin.locator('[name=name]').fill(clientDetails.contactName);
  await admin.locator('[name=email]').fill(clientDetails.email);
  await admin.locator('#invitation-create button').click();
  await admin.locator('#invitation-result').waitFor({state:'visible'});
  const url=await admin.locator('#invitation-link').inputValue();
  assert.match(url,/#invite=[A-Za-z0-9_-]{43}$/);
  await admin.waitForFunction(()=>document.querySelector('#invitation-delivery').textContent.includes('accepted for delivery'));
  assert.equal(invitationEmails.length,1);assert.equal(invitationEmails[0].url,url);assert.equal(invitationEmails[0].invitation.email,clientDetails.email);
  await client.goto(url);
  await client.waitForFunction(()=>!document.querySelector('#client-details-form').inert);
  assert.equal(await client.locator('#client-email').inputValue(),clientDetails.email);
  assert.equal(await client.locator('#client-email').evaluate(input=>input.readOnly),true);
  assert.equal(await client.locator('#client-contact').inputValue(),clientDetails.contactName);
  assert.equal(new URL(client.url()).hash,'');
  for(const [name,value] of Object.entries(clientDetails)){const field=client.locator(`#client-details-form [name="${name}"]`);if(await field.count() && name!=='email')await field.fill(name==='phone'?value.slice(-10):value);}
  await client.locator('#client-details-form button[type=submit]').click();
  await client.locator('#package-stage').waitFor({state:'visible'});
  await client.locator('#package-form button[type=submit]').click();
  assert.equal(await client.locator('#main').isVisible(),true);
  assert.equal(await client.locator('#agreement-form').evaluate(form=>form.inert),false);
  await other.goto(url);
  await other.locator('#invitation-stage').waitFor({state:'visible'});
  assert.match(await other.locator('#invitation-message').innerText(),/another browser/);
  assert.equal(await other.locator('#client-email').inputValue(),'');
  await admin.locator('#invitation-refresh').click();
  await admin.waitForFunction(()=>document.querySelector('#invitation-list').textContent.includes('opened'));
  await mkdir('artifacts',{recursive:true});
  await admin.screenshot({path:'artifacts/invitation-admin-desktop.png',fullPage:true});
  await admin.setViewportSize({width:390,height:844});
  await admin.screenshot({path:'artifacts/invitation-admin-mobile.png',fullPage:true});
  assert.equal(await admin.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
  admin.once('dialog',dialog=>dialog.accept());
  await admin.locator('#invitation-list button').click();
  await admin.waitForFunction(()=>document.querySelector('#invitation-list').textContent.includes('revoked'));
  await client.reload();
  await client.locator('#invitation-stage').waitFor({state:'visible'});
  assert.match(await client.locator('#invitation-message').innerText(),/revoked/);
  await admin.locator('#admin-logout').click();
  assert.equal(await admin.locator('#admin-login').isVisible(),true);
  assert.equal(await admin.locator('#invitation-link').inputValue(),'');
  await admin.reload();assert.equal(await admin.locator('#admin-content').isVisible(),false);
  config.email.enabled=false;
  await admin.locator('#admin-key').fill(adminKey);
  await admin.locator('#admin-login button').click();
  await admin.locator('#admin-content').waitFor({state:'visible'});
  assert.match(await admin.locator('#invitation-email-settings').innerText(),/EMAIL_ENABLED=true/);
  assert.equal(await admin.locator('#invitation-create button').innerText(),'Create invitation link');
  assert.deepEqual(errors,[]);
  console.log('Invitation browser checks passed: hosting error handling, access cookies, admin auth, create, public gate, invited email, one browser, revocation, logout and mobile layout.');
}finally{await browser?.close();await new Promise(resolve=>{server.close(resolve);server.closeAllConnections();});}
